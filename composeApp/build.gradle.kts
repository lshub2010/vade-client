compose.desktop {
    application {
        mainClass = "vade.ui.MainKt"
        nativeDistributions {
            // jpackage on Windows can only emit Msi/Exe, and BOTH need the WiX 3.x
            // toolset. A5 ships the toolset-free path: `createDistributable` produces the
            // self-contained app-image (bundled jlink runtime — starts on a clean
            // machine). Msi preconditions are documented in deploy/desktop/README.md.
            targetFormats(TargetFormat.Msi)
            packageName = "vade-ui"
            // jpackage product version must be numeric x.y.z — the `-alpha.N` pre-release
            // suffix is not representable, so it is DERIVED from the single source below,
            // never a second hardcoded version.
            packageVersion = vadeVersion.substringBefore('-')
            vendor = "Vade"
        }
    }
}

// --- helpers for the real-window screenshot loop (ui/tools/capture-window.ps1) ---
val desktopMainCompilation = kotlin.targets.getByName("desktop").compilations.getByName("main")

// Prints the runtime classpath so the PowerShell capture script can `java -cp` the
// app without paying Gradle configuration for every shot.
tasks.register("printRuntimeClasspath") {
    doLast {
        println(
            files(desktopMainCompilation.output.allOutputs, desktopMainCompilation.runtimeDependencyFiles).asPath,
        )
    }
}
