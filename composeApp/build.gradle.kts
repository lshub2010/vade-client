    namespace = "vade.ui"
    // 37, not 36: the compose/material3 AARs pulled by CMP 1.12 declare
    // minCompileSdk=37, and AGP < 9.1 cannot resolve platforms;android-37.0.
    compileSdk = 37

    defaultConfig {
        applicationId = "vade.ui"
        minSdk = 24
        targetSdk = 36
        versionCode = 1
        // A5 · derived from gradle.properties `vadeVersion` — no second version literal.
        versionName = vadeVersion
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    packaging {
        resources.excludes += setOf("/META-INF/{AL2.0,LGPL2.1}")
    }
