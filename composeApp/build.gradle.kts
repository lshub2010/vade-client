// --- A5 · version single source ------------------------------------------------
// `vadeVersion` in the repo-root gradle.properties is the ONLY place the version is
// written. Everything else derives from it:
//   - generateVadeBuildConfig stamps it into the generated VadeBuildConfig (关于 page),
//   - the Android versionName and the jpackage packageVersion come from the same val.
// Fail fast at configuration time: a silently-empty version would ship a lying 关于 page.
val vadeVersion = (project.findProperty("vadeVersion") as? String)?.trim().orEmpty().also {
    require(it.isNotEmpty()) { "gradle.properties must define vadeVersion (A5 single version source)" }
}

// Stamps `vadeVersion` (plus the UTC build time) into a generated commonMain source so
// all three targets and the tests read the same constant. The output is regenerated on
// every build — never edit it by hand, and never introduce a second version literal.
val generateVadeBuildConfig = tasks.register("generateVadeBuildConfig") {
    val outDir = layout.buildDirectory.dir("generated/vadeBuildConfig")
    val version = vadeVersion
    outputs.dir(outDir)
    doLast {
        val buildTime = DateTimeFormatter
            .ofPattern("yyyy-MM-dd'T'HH:mm:ss'Z'")
            .withZone(ZoneOffset.UTC)
            .format(Instant.now())
        val dir = outDir.get().asFile.resolve("vade/ui/buildconfig")
        dir.mkdirs()
        File(dir, "VadeBuildConfig.kt").writeText(
            """
            // GENERATED by `generateVadeBuildConfig` (composeApp/build.gradle.kts) — DO NOT EDIT.
            // Source of truth: `vadeVersion` in the repo-root gradle.properties.
            package vade.ui.buildconfig

            /** Version facts injected at build time (A5 single source). */
            object VadeBuildConfig {
                const val VERSION: String = "$version"
                const val BUILD_TIME: String = "$buildTime"
            }
            """.trimIndent(),
        )
    }
}

kotlin {
    androidTarget {
        compilerOptions {
            jvmTarget.set(JvmTarget.JVM_17)
        }
    }

    // JVM 17, not "whatever JDK Gradle runs on": the daemon here is JDK 26, and without
    // an explicit target the desktop classes come out as class-file 70, which the JDK 21
    // used to launch/screenshot the app cannot load. Task book T1 asks for Desktop JVM 17.
    jvm("desktop") {
        compilerOptions {
            jvmTarget.set(JvmTarget.JVM_17)
        }
    }

    @OptIn(org.jetbrains.kotlin.gradle.ExperimentalWasmDsl::class)
    wasmJs {
        // `moduleName` was renamed to `outputModuleName` in KGP 1.9; 2.4.20 has no
        // `moduleName` accessor at all (the build script would not compile).
        outputModuleName = "composeApp"
        browser {
            commonWebpackConfig {
                outputFileName = "composeApp.js"
            }
        }
        binaries.executable()
    }

    sourceSets {
        val desktopMain by getting
        val wasmJsMain by getting

        // A5 · the generated VadeBuildConfig joins commonMain so all three targets (and
        // the tests) see the same constant; srcDir(TaskProvider) wires the task as an
        // input dependency of every compilation that consumes the source set.
        commonMain {
            kotlin.srcDir(generateVadeBuildConfig)
        }

        commonMain.dependencies {
            implementation(compose.runtime)
            implementation(compose.foundation)
            implementation(compose.ui)
            implementation(compose.material3)
            // U2 · miuix skin. Version + matrix come straight from spike/miuix/versions.lock.md:
            // 0.9.4 is the newest stable, compiled against Kotlin 2.4.20 / CMP 1.12.0 (both
            // already pinned in the root build), and its four Android AARs declare
            // minCompileSdk=37 (this module is already on 37). No AGP/Gradle/compileSdk change.
            implementation("top.yukonga.miuix.kmp:miuix-ui:0.9.4")
            // w2-bottombar · KernelSU-style floating pill. miuix-blur is a *separate*
            // artifact from miuix-ui (same version line, four variants: android /
            // desktop / js / wasmJs); it provides rememberLayerBackdrop /
            // Modifier.layerBackdrop / drawBackdrop + BackdropEffectScope (blur /
            // colorControls / runtimeShaderEffect) and the BloomStroke highlight.
            // Consumed ONLY via vade.ui.component.liquid (shell must stay toolkit-free).
            implementation("top.yukonga.miuix.kmp:miuix-blur:0.9.4")
            // v2 Wave 0 · real backdrop blur (docs/visual-language.md §5). 2.1.0 is the
            // probe-verified version (shots of tmp/haze-probe: three targets compile, desktop
            // really blurs); its `androidApiElements` / `jvmApiElements` / `wasmJsApiElements`
            // variants cover all three targets of this module. The tint MUST go through
            // `colorEffects(...)` — `backgroundColor` paints behind the opaque blurred layer
            // and is a no-op (probe RESULT.md §坑1).
            implementation("dev.chrisbanes.haze:haze:2.1.0")
            implementation("dev.chrisbanes.haze:haze-blur:2.1.0")
            // v2 Wave 0 · SessionSource transport seam. Ktor 3.6.1 = newest stable line on
            // Maven Central (metadata lastUpdated 2026-10-29); its Gradle module metadata
            // declares kotlin-stdlib 2.3.21, which the 2.4.20 compiler of this repo reads
            // (metadata is read one minor ahead), and the wasmJsApiElements variant exists
            // for every artifact below — verified against repo1.maven.org, not from memory.
            // Engines are per-target below; only the core/websockets/content-negotiation/
            // serialization contracts live in commonMain so `data/` stays engine-free.
            implementation("io.ktor:ktor-client-core:3.6.1")
            implementation("io.ktor:ktor-client-websockets:3.6.1")
            implementation("io.ktor:ktor-client-content-negotiation:3.6.1")
            implementation("io.ktor:ktor-serialization-kotlinx-json:3.6.1")
            // w2-icons · Tabler Icons as vector ImageVectors (docs/visual-language.md §3:
            // icons are vectors, never glyphs/CJK chars). Three coordinates, verified against
            // the 2.2.1 artifacts on Maven Central (jar listings, not from memory):
            //  - icons-tabler-cmp         = the `Tabler` namespace object only (2.4 KB stub);
            //                               also the license umbrella (MIT).
            //  - icons-tabler-outline-cmp = `Tabler.Outline.*` extension properties (4 985 icons).
            //  - icons-tabler-filled-cmp  = `Tabler.Filled.*` (the one fill icon: PlayerStop).
            // All three publish jvm / wasm-js / android variants. Business code must not
            // import `com.composables.icons.tabler.*` — it goes through `vade.ui.icon.VadeIcons`.
            implementation("com.composables:icons-tabler-cmp:2.2.1")
            implementation("com.composables:icons-tabler-outline-cmp:2.2.1")
            implementation("com.composables:icons-tabler-filled-cmp:2.2.1")
        }

        desktopMain.dependencies {
            implementation(compose.desktop.currentOs)
            // CIO engine: pure JVM, no extra native deps — the desktop default for Ktor 3.x.
            implementation("io.ktor:ktor-client-cio:3.6.1")
        }

        androidMain.dependencies {
            // Same version the spike used; no bump.
            implementation("androidx.activity:activity-compose:1.9.3")
            // OkHttp engine: the Android-recommended engine, backed by the platform's
